"""Exercise local Git storage checks in fixtures; no network or user repositories."""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

SCRIPTS = Path(__file__).resolve().parents[1] / "skills/computer-repair-skill/scripts"
sys.path.insert(0, str(SCRIPTS))
_write_bytecode = sys.dont_write_bytecode
try:
    sys.dont_write_bytecode = True  # Keep generated bytecode out of the installable Skill.
    import git_storage_audit as auditor
finally:
    sys.dont_write_bytecode = _write_bytecode


@unittest.skipUnless(shutil.which("git"), "Git required")
class GitStorageAuditTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="repair git audit ")
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name).resolve()
        self.repo = self.base / "repo with spaces"
        self.repo.mkdir()
        self.git("init", "-b", "main")
        self.git("config", "user.name", "Fixture")
        self.git("config", "user.email", "fixture@example.invalid")
        self.git("config", "commit.gpgsign", "false")
        self.git("config", "core.hooksPath", str(self.base / "absent-hooks"))
        (self.repo / "tracked.txt").write_text("baseline\n")
        (self.repo / ".gitignore").write_text("ignored/\n")
        self.git("add", ".")
        self.git("commit", "-m", "fixture")

    def git(self, *args):
        result = subprocess.run(["git", "-C", str(self.repo), *args],
                                env=auditor.git_environment(), capture_output=True, timeout=15)
        self.assertEqual(result.returncode, 0, result.stderr.decode(errors="replace"))
        return result.stdout.decode("utf-8").strip()

    def snapshot(self):
        return {str(p.relative_to(self.base)): hashlib.sha256(p.read_bytes()).hexdigest()
                for p in self.base.rglob("*") if p.is_file()}

    def test_local_data_and_stash_are_reported_without_writes(self):
        (self.repo / "tracked.txt").write_text("stash work\n")
        self.git("stash", "push", "-m", "private message not for reports")
        (self.repo / "tracked.txt").write_text("local work\n")
        (self.repo / "untracked.txt").write_text("only here\n")
        (self.repo / "ignored").mkdir()
        (self.repo / "ignored/data.txt").write_text("unique ignored data\n")
        before = self.snapshot()
        report = auditor.audit(self.repo, timeout=30)
        self.assertTrue(report["complete"], report)
        self.assertEqual(report["status"]["tracked_changes"], 1)
        self.assertEqual(report["status"]["untracked_entries"], 1)
        self.assertEqual(report["status"]["ignored_entries"], 1)
        self.assertEqual(report["stash"]["observed_count"], 1)
        self.assertNotIn("private message", json.dumps(report))
        self.assertEqual(before, self.snapshot())

    def test_cached_remote_is_never_proof_of_backup(self):
        self.git("remote", "add", "origin", "https://example.invalid/private-repository.git")
        self.git("update-ref", "refs/remotes/origin/main", "HEAD")
        before = self.snapshot()
        report = auditor.audit(self.repo, timeout=30)
        self.assertTrue(report["complete"], report)
        self.assertEqual(report["commits_not_in_cached_remotes"], 0)
        self.assertFalse(report["remote_verified"])
        self.assertNotIn("example.invalid", json.dumps(report))
        self.assertEqual(before, self.snapshot())

    def test_worktrees_and_gitlinks_require_separate_inspection(self):
        linked = self.base / "linked workspace"
        self.git("worktree", "add", "-b", "local-feature", str(linked))
        oid = self.git("rev-parse", "HEAD")
        self.git("update-index", "--add", "--cacheinfo", "160000", oid, "module")
        report = auditor.audit(self.repo, timeout=30)
        self.assertTrue(report["complete"], report)
        self.assertEqual(report["worktrees"]["observed_count"], 2)
        self.assertEqual(report["submodules"]["samples"], ["module"])
        self.assertFalse(report["submodules"]["worktrees_inspected"])
        linked_report = auditor.audit(linked, timeout=30)
        self.assertTrue(linked_report["complete"], linked_report)
        self.assertNotEqual(linked_report["git_dir"], linked_report["common_dir"])
        self.assertTrue(linked_report["external_git_metadata"])

    def test_rename_and_unusual_names_do_not_corrupt_counts(self):
        self.git("mv", "tracked.txt", "renamed with spaces.txt")
        name = "new file.txt" if os.name == "nt" else "line\nbreak.txt"
        (self.repo / name).write_text("new\n")
        report = auditor.audit(self.repo, timeout=30)
        self.assertTrue(report["complete"], report)
        self.assertEqual(report["status"]["tracked_changes"], 1)
        self.assertEqual(report["status"]["untracked_entries"], 1)
        self.assertTrue(any(sample.get("original_path") == "tracked.txt"
                            for sample in report["status"]["samples"]))
        self.assertTrue(any(sample["path"] == name for sample in report["status"]["samples"]))
        limited = auditor.audit(self.repo, samples=0, timeout=30)
        self.assertTrue(limited["complete"], limited)
        self.assertEqual(limited["status"]["samples"], [])
        self.assertEqual(limited["status"]["untracked_entries"], 1)

    def test_repository_filters_are_not_executed(self):
        (self.repo / "sample.dat").write_text("abc\n")
        (self.repo / ".gitattributes").write_text("*.dat filter=fixture\n")
        self.git("add", ".")
        self.git("commit", "-m", "data fixture")
        marker = self.base / "filter-executed.txt"
        program = self.base / "filter.py"
        program.write_text("import pathlib, sys\npathlib.Path(" + repr(str(marker))
                           + ").write_text('executed')\nsys.stdout.write(sys.stdin.read())\n")
        command = '"' + Path(sys.executable).as_posix() + '" "' + program.as_posix() + '"'
        self.git("config", "filter.fixture.clean", command)
        self.git("config", "filter.fixture.required", "true")
        (self.repo / "sample.dat").write_text("xyz\n")
        before = self.snapshot()
        report = auditor.audit(self.repo, timeout=30)
        self.assertTrue(report["complete"], report)
        self.assertTrue(report["filters_disabled"])
        self.assertFalse(marker.exists())
        self.assertEqual(before, self.snapshot())
        # Positive control: the fixture's configured filter really is executable.
        self.git("hash-object", "--path=sample.dat", "sample.dat")
        self.assertTrue(marker.exists())

    def test_inherited_git_directory_cannot_redirect_audit(self):
        (self.repo / "visible.txt").write_text("local\n")
        with patch.dict(os.environ, {"GIT_DIR": str(self.base / "absent"),
                                     "GIT_WORK_TREE": str(self.base / "wrong"),
                                     "GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": "core.bare",
                                     "GIT_CONFIG_VALUE_0": "true"}):
            report = auditor.audit(self.repo, timeout=30)
        self.assertTrue(report["complete"], report)
        self.assertEqual(report["status"]["untracked_entries"], 1)

    def test_missing_unborn_and_bare_repositories_remain_unknown(self):
        self.assertFalse(auditor.audit(self.base / "missing")["complete"])
        self.assertFalse(auditor.audit(self.base)["complete"])
        for name, args in (("unborn", []), ("bare", ["--bare"])):
            target = self.base / name
            self.git("init", *args, str(target))
            report = auditor.audit(target, timeout=30)
            self.assertFalse(report["complete"], report)
            self.assertFalse(report["remote_verified"])

    def test_time_and_output_limits_cannot_produce_clean_report(self):
        for timeout in (float("nan"), float("inf"), 0, -1, 301):
            with self.assertRaises(ValueError):
                auditor.audit(self.repo, timeout=timeout)
        report = auditor.audit(self.repo, timeout=1e-12)
        self.assertFalse(report["complete"])
        self.assertTrue(report["checks"]["repository"]["timed_out"])
        with patch.object(auditor, "OUTPUT_LIMIT", 8):
            report = auditor.audit(self.repo, timeout=30)
        self.assertFalse(report["complete"])
        self.assertTrue(report["checks"]["repository"]["output_truncated"])

    def test_cli_returns_json_and_distinguishes_incomplete_checks(self):
        for target, expected in ((self.repo, 0), (self.base, 2)):
            result = subprocess.run([sys.executable, str(SCRIPTS / "git_storage_audit.py"),
                                     str(target), "--timeout", "30"],
                                    capture_output=True, timeout=40)
            self.assertEqual(result.returncode, expected, result.stderr)
            self.assertEqual(json.loads(result.stdout)["complete"], expected == 0)


if __name__ == "__main__":
    unittest.main()
